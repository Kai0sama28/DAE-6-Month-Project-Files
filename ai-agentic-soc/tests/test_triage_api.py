REPORT_HTML = "<html><body><h1>Incident Report SOC-20261026-001</h1></body></html>"


def _write_report(root: Path) -> Path:
    path = root / "SOC-20261026-001.md"
    path.write_text(REPORT_MD, encoding="utf-8")
    path.with_suffix(".html").write_text(REPORT_HTML, encoding="utf-8")
    return path


def _wait_for_job(client: TestClient, job_id: str) -> Dict[str, Any]:
    for _ in range(200):
        response = client.get("/api/v1/jobs/%s" % job_id)
        assert response.status_code == 200
        data = response.json()
        if data["status"] in ("succeeded", "failed"):
            return data
        time.sleep(0.01)
    raise AssertionError("job did not finish")


def test_health_and_case_endpoints(tmp_path: Path):
    _write_report(tmp_path)
    app = create_app(reports_dir=tmp_path, decisions_path=tmp_path / "decisions.json")
    with TestClient(app) as client:
        health = client.get("/api/v1/health")
        assert health.status_code == 200
        assert health.json()["status"] == "ok"
        assert health.json()["worker_alive"] is True

        cases = client.get("/api/v1/cases").json()
        assert len(cases) == 1
        assert cases[0]["incident_id"] == "SOC-20261026-001"
        assert cases[0]["severity"] == "Medium"
        assert cases[0]["confidence"] == "High"

        detail = client.get("/api/v1/cases/SOC-20261026-001")
        assert detail.status_code == 200
        payload = detail.json()
        assert payload["attack_duration"] == "58.1s"
        assert payload["correlated_events"] == "44"
        assert "Executive Summary" in payload["markdown"]
        assert payload["report_html_path"].endswith(".html")

        markdown = client.get("/api/v1/cases/SOC-20261026-001/report")
        assert markdown.status_code == 200
        assert markdown.text.startswith("# Incident Report")

        html = client.get("/api/v1/cases/SOC-20261026-001/report", params={"format": "html"})
        assert html.status_code == 200
        assert "<html>" in html.text

        metrics = client.get("/api/v1/metrics").json()
        assert metrics["total_cases"] == 1
        assert metrics["by_severity"] == {"Medium": 1}
        assert metrics["by_decision"] == {"pending": 1}


def test_decision_is_persisted_in_case(tmp_path: Path):
    _write_report(tmp_path)
    app = create_app(reports_dir=tmp_path, decisions_path=tmp_path / "decisions.json")
    with TestClient(app) as client:
        response = client.post(
            "/api/v1/cases/SOC-20261026-001/decision",
            json={"decision": "approved", "analyst": "Kyrell", "note": "Containment approved."},
        )
        assert response.status_code == 200
        assert response.json()["decision"] == "approved"

        case = client.get("/api/v1/cases/SOC-20261026-001").json()
        assert case["decision"]["analyst"] == "Kyrell"
        assert case["decision"]["note"] == "Containment approved."

        response = client.post(
            "/api/v1/cases/SOC-20261026-001/decision",
            json={"decision": "maybe", "analyst": "Kyrell"},
        )
        assert response.status_code == 422

        missing = client.post(
            "/api/v1/cases/SOC-20261026-999/decision",
            json={"decision": "approved", "analyst": "Kyrell"},
        )
        assert missing.status_code == 404


def test_investigation_job_runs_and_succeeds(tmp_path: Path):
    seen = []

    def fake_executor(alert_id: str) -> Dict[str, Any]:
        seen.append(alert_id)
        return {
            "alert_id": alert_id,
            "incident_id": "SOC-20261026-001",
            "status": "report_ready",
            "report_path": str(tmp_path / "SOC-20261026-001.md"),
            "report_html_path": str(tmp_path / "SOC-20261026-001.html"),
            "severity": "Medium",
            "confidence": "High",
        }

    app = create_app(
        reports_dir=tmp_path,
        decisions_path=tmp_path / "decisions.json",
        executor=fake_executor,
    )
    with TestClient(app) as client:
        response = client.post("/api/v1/investigations", json={"alert_id": "alert-1"})
        assert response.status_code == 202
        job_id = response.json()["job_id"]
        job = _wait_for_job(client, job_id)
        assert job["status"] == "succeeded"
        assert job["result"]["incident_id"] == "SOC-20261026-001"
        assert seen == ["alert-1"]

        jobs = client.get("/api/v1/jobs").json()
        assert jobs[0]["job_id"] == job_id


def test_duplicate_active_job_is_deduplicated(tmp_path: Path):
    started = threading.Event()
    release = threading.Event()

    def blocking_executor(alert_id: str) -> Dict[str, Any]:
        started.set()
        release.wait(5)
        return {"alert_id": alert_id}

    app = create_app(
        reports_dir=tmp_path,
        decisions_path=tmp_path / "decisions.json",
        executor=blocking_executor,
    )
    with TestClient(app) as client:
        first = client.post("/api/v1/investigations", json={"alert_id": "alert-2"}).json()
        assert started.wait(5)
        second = client.post("/api/v1/investigations", json={"alert_id": "alert-2"}).json()
        assert second["job_id"] == first["job_id"]
        forced = client.post(
            "/api/v1/investigations",
            json={"alert_id": "alert-2", "force": True},
        ).json()
        assert forced["job_id"] != first["job_id"]
        release.set()
        _wait_for_job(client, first["job_id"])
        _wait_for_job(client, forced["job_id"])


def test_failed_job_records_error(tmp_path: Path):
    def failing_executor(alert_id: str) -> Dict[str, Any]:
        raise RuntimeError("indexer unavailable")

    app = create_app(
        reports_dir=tmp_path,
        decisions_path=tmp_path / "decisions.json",
        executor=failing_executor,
    )
    with TestClient(app) as client:
        response = client.post("/api/v1/investigations", json={"alert_id": "alert-3"})
        job = _wait_for_job(client, response.json()["job_id"])
        assert job["status"] == "failed"
        assert "RuntimeError: indexer unavailable" in job["error"]
